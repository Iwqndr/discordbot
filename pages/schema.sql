-- ===========================================================================
-- wispcord member page — Cloudflare Pages Functions schema
--
-- Paste this whole file into the Supabase SQL Editor and press Run. It is
-- idempotent: every statement is safe to run more than once, and it does not
-- touch the tables the admin/member bots already own.
--
-- Access model, in one paragraph. The browser holds the **anon** key (it is
-- baked into member.html), so the anon key must never be able to read anything
-- private. Every table below therefore has RLS enabled with **no anon policy at
-- all**: the Cloudflare Worker reads and writes them with
-- SUPABASE_SERVICE_KEY, which is a Pages secret and never reaches a browser.
-- The Worker is what enforces "this ticket is yours", using the signed session
-- cookie — so the rule is enforced in one place, not in a policy an attacker
-- could query around.
--
-- The two exceptions are the tables the page still fetches directly with the
-- anon key: `bot_status` (already readable, see wispbyte_schema.sql) and
-- `members` (already readable today). Nothing here changes those.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. ticket_queue — new tickets, exactly as wispbyte_schema.sql defines them
--    (recreated here so this file stands alone; if it already exists the body
--    is left alone and only the RLS policies are refreshed)
-- ---------------------------------------------------------------------------
create table if not exists public.ticket_queue (
  id              bigint generated by default as identity primary key,
  ticket_id       text,
  category        text,
  category_label  text,
  subject         text,
  body            text,
  contact         text,
  priority        text default 'normal',
  answers         jsonb default '{}'::jsonb,
  attachments     jsonb default '[]'::jsonb,
  discord_user_id text,
  discord_tag     text,
  anonymous       boolean default false,
  status          text default 'queued',
  created_at      timestamptz default now(),
  processed_at    timestamptz
);

-- Columns added after the first release are patched in one at a time, because
-- `create table if not exists` will not add them to an existing table.
alter table public.ticket_queue add column if not exists category_label text;
alter table public.ticket_queue add column if not exists contact text;
alter table public.ticket_queue add column if not exists priority text default 'normal';

create index if not exists ticket_queue_unprocessed_idx
  on public.ticket_queue (processed_at) where processed_at is null;

alter table public.ticket_queue enable row level security;

-- No anon policy: the Worker uses the service key. Dropping the older
-- browser-insert policy is deliberate — the Worker is the only writer now, so
-- the `discord_user_id` on a ticket is always the id it verified.
drop policy if exists "anon can insert tickets" on public.ticket_queue;
drop policy if exists "service full access ticket_queue" on public.ticket_queue;
create policy "service full access ticket_queue"
  on public.ticket_queue
  for all
  to service_role
  using (true)
  with check (true);

