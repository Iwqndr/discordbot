-- ---------------------------------------------------------------------------
-- 5. staff_titles — the badge rules the member page applies to names
--
--    Shape per row:
--      roles    jsonb  ["<role id>", ...]      matched against the member's roles
--      keywords jsonb  ["moderator", ...]      matched against role names
--      style    jsonb  the admin bot's style object
--                      (effect, colors, font, weight, size, spacing, italic,
--                       uppercase, fill, radius, pad_x, pad_y, border, glow)
--    Priority decides the winner when more than one rule matches.
-- ---------------------------------------------------------------------------
create table if not exists public.staff_titles (
  id         text primary key,
  label      text not null,
  prefix     text,
  suffix     text,
  priority   integer default 0,
  roles      jsonb default '[]'::jsonb,
  keywords   jsonb default '[]'::jsonb,
  style      jsonb default '{}'::jsonb,
  created_at timestamptz default now()
);

alter table public.staff_titles enable row level security;

drop policy if exists "service full access staff_titles" on public.staff_titles;
create policy "service full access staff_titles"
  on public.staff_titles
  for all
  to service_role
  using (true)
  with check (true);

