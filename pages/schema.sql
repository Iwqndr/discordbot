-- ---------------------------------------------------------------------------
-- 6b. economy — a READ-ONLY mirror of the member bot's JSON balances
--
--     The bot keeps economy.json as its source of truth and republishes every
--     record here once a minute, so the member site can show coins and levels
--     without reaching into the bot's disk.
--
--     anon may SELECT this: it is public game data, the same numbers every
--     member can already see with `>baltop`. There is deliberately no anon
--     write policy — only the bot (service key) may update it.
-- ---------------------------------------------------------------------------
create table if not exists public.economy (
  user_id    text primary key,
  balance    bigint default 0,
  bank       bigint default 0,
  xp         integer default 0,
  level      integer default 1,
  wins       integer default 0,
  losses     integer default 0,
  streak     integer default 0,
  updated_at timestamptz default now()
);

alter table public.economy enable row level security;

drop policy if exists "anon can read economy" on public.economy;
create policy "anon can read economy"
  on public.economy
  for select
  to anon
  using (true);

drop policy if exists "service full access economy" on public.economy;
create policy "service full access economy"
  on public.economy
  for all
  to service_role
  using (true)
  with check (true);

-- ---------------------------------------------------------------------------
-- 7. Storage bucket for ticket attachments
--    Public to read (a ticket reply has to render the image), writable only
--    with the service key the Worker holds.
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('ticket-attachments', 'ticket-attachments', true)
on conflict (id) do nothing;

drop policy if exists "service can write ticket attachments" on storage.objects;
create policy "service can write ticket attachments"
  on storage.objects
  for insert
  to service_role
  with check (bucket_id = 'ticket-attachments');

drop policy if exists "anyone can read ticket attachments" on storage.objects;
create policy "anyone can read ticket attachments"
  on storage.objects
  for select
  to anon, authenticated
  using (bucket_id = 'ticket-attachments');

