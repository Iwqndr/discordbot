-- ---------------------------------------------------------------------------
-- 3. member_tickets — the member-visible index of their own tickets
--
--    Rows are written by the Worker when a ticket is opened and kept in step
--    by the admin bot: when staff reply it appends to `replies`, when it closes
--    the ticket it sets `status = 'closed'`.
-- ---------------------------------------------------------------------------
create table if not exists public.member_tickets (
  id              bigint generated by default as identity primary key,
  ticket_id       text not null unique,
  category        text,
  category_label  text,
  subject         text,
  contact         text,
  priority        text default 'normal',
  answers         jsonb default '{}'::jsonb,
  attachments     jsonb default '[]'::jsonb,
  replies         jsonb default '[]'::jsonb,
  discord_user_id text not null,
  discord_tag     text,
  status          text default 'open',
  created_at      timestamptz default now(),
  updated_at      timestamptz default now(),
  closed_at       timestamptz
);

create index if not exists member_tickets_user_idx
  on public.member_tickets (discord_user_id, created_at desc);

alter table public.member_tickets enable row level security;

drop policy if exists "service full access member_tickets" on public.member_tickets;
create policy "service full access member_tickets"
  on public.member_tickets
  for all
  to service_role
  using (true)
  with check (true);

